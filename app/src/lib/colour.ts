// Colour arithmetic for the palettes: mixing, and which text an accent fill can carry.

function channels(hex: string): [number, number, number] {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/** `base` with `amount` (0..1) of `tint` mixed in, as a hex colour. */
export function mix(base: string, tint: string, amount: number): string {
  const a = channels(base);
  const b = channels(tint);
  return `#${a.map((v, i) => Math.round(v + (b[i] - v) * amount).toString(16).padStart(2, "0")).join("")}`;
}

/** WCAG relative luminance of a hex colour. */
export function luminance(hex: string): number {
  const [r, g, b] = channels(hex).map((v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/**
 * Text on an accent fill: white, unless white cannot be read on it. A pale accent (the dark
 * mode's greens, blues and the mono grey) takes near-black, which it carries clearly.
 */
export function textOnAccent(accent: string): string {
  const whiteContrast = 1.05 / (luminance(accent) + 0.05);
  return whiteContrast < 2.6 ? "#141416" : "#fff";
}
